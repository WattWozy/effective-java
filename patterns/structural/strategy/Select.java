
public class Select{

    public static double sum(int a, int b){
        return (double) a + b;
    }
    public static double sub(int a, int b){
        return  (double) a - b;
    }
    public static double mul(int a, int b){
        return  (double) a * b;
    }
    public static double div(int a, int b){
        return  (double) a / b;
    }

}